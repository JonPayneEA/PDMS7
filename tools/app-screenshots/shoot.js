const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 });
  const idle = async () => { await p.waitForFunction(() => !document.documentElement.classList.contains('shiny-busy')); await p.waitForTimeout(1200); };
  const clear = async () => { await p.evaluate(() => document.querySelectorAll('.shiny-notification').forEach(n => n.remove())); };
  const pane = async (name) => { await clear(); await (await p.$('.tab-pane.active')).screenshot({ path: 'shots/' + name + '.png' }); };
  const el = async (name, sel) => { await clear(); await (await p.$(sel)).screenshot({ path: 'shots/' + name + '.png' }); };
  const sel = async (id, v) => { await p.evaluate(([id, v]) => $('#' + id)[0].selectize.setValue(v), [id, v]); await idle(); };
  await p.goto('http://127.0.0.1:8765'); await idle();
  await p.click('#open'); await idle();
  await p.click('a[data-value="Events"]'); await idle();
  await p.fill('#wb_n', '6'); await idle();
  await p.click('#wb_load'); await p.waitForSelector('#wb_plot img'); await idle();
  await clear(); await p.screenshot({ path: 'shots/app-events-loaded.png', fullPage: true });
  await p.evaluate(() => { for (const [id, v] of [['p_wb__surface__k1', 2], ['p_wb__surface__k2', 4], ['p_wb__td', 3]]) $('#' + id).data('ionRangeSlider').update({ from: v }); });
  await p.waitForTimeout(800); await idle(); await p.waitForTimeout(1500); await idle();
  await pane('app-events-moved');
  await p.check('input[name="wb_verdict"][value="better"]');
  await p.fill('#wb_reasoning', 'Faster stores and a 3 h delay put all six peaks on time. Peaks now 13% high: refit the rest.');
  await el('app-events-verdict', '.tab-pane.active .well');
  await p.click('#wb_save'); await idle();
  await p.click('#wb_recession'); await p.waitForSelector('#wb_recession_plot img', { timeout: 120000 }); await idle();
  await el('app-events-recession', '#wb_recession_plot');
  await p.click('a[data-value="Trial"]'); await idle(); await p.waitForTimeout(1500);
  await sel('parent', '0009');
  await sel('calib_params', ['fc', 'distribution.cmax', 'distribution.b', 'recharge.kg']);
  await p.fill('#calib_reasoning', 'Refit the volume and recharge parameters around the stores and delay set on the Events tab.');
  await clear();
  const box = await p.evaluate(() => { const w = document.querySelector('.tab-pane.active .well').getBoundingClientRect(); const h = [...document.querySelectorAll('.tab-pane.active h4')].find(x => x.textContent.includes('Automatic')).getBoundingClientRect(); const r = document.querySelector('#run_calib').getBoundingClientRect(); return { x: w.x, y: h.y + window.scrollY - 12, width: w.width, height: r.bottom - h.y + 24 }; });
  await p.screenshot({ path: 'shots/app-trial-refit.png', clip: box, fullPage: true });
  await p.click('#run_calib'); await idle(); await p.waitForTimeout(3000); await idle();
  await p.click('a[data-value="Events"]'); await idle();
  await sel('wb_parent', '0010'); await p.click('#wb_load'); await idle(); await p.waitForTimeout(1500); await idle();
  await pane('app-events-refit');
  await p.click('a[data-value="History"]'); await idle(); await p.waitForTimeout(2000);
  await sel('compare_a', '0006'); await sel('compare_b', '0010'); await sel('candidate_entry', '0010');
  await p.waitForTimeout(2000); await idle();
  await p.fill('#candidate_reasoning', 'Run 0010: the stores and delay set by eye on the largest events, then the rest refitted. Peaks on time and to size.');
  await p.click('#propose'); await idle();
  await p.fill('#validation_reasoning', 'Validation scores match calibration; the peaks hold up outside the calibration years.');
  await p.click('#validate'); await p.waitForSelector('#validation_scores table', { timeout: 120000 }); await idle();
  await pane('app-history');
  await b.close();
})();
